package dev.ferrite.server;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

/** Block-state fidelity on the world-level write path, and {@code World#loadChunk} through the host. */
class WorldChunkContentTest {
    private static org.bukkit.World world;

    @BeforeAll static void start() {
        System.setProperty("ferrite.native", "false");
        Bootstrap.configureDataDir(System.getProperty("test.vanilla.data"));
        Bootstrap.startServer();
        Bootstrap.registerWorld("00000000-0000-0000-0000-0000000000f8", "chunk_content_world", 0, 0, 64, 0);
        world = org.bukkit.Bukkit.getWorld("chunk_content_world");
    }

    @AfterAll static void stop() {
        if (world != null) ((FerriteServer) org.bukkit.Bukkit.getServer()).unregisterWorld(world.getUID());
    }

    @Test void worldSetBlockDataKeepsTheFullStateAndGetBlockDataReadsItBack() {
        var stairs = "minecraft:oak_stairs[facing=east,half=top,shape=straight,waterlogged=false]";
        world.setBlockData(10, 70, 10, FerriteBlockData.create(stairs));
        assertEquals(org.bukkit.Material.OAK_STAIRS, world.getType(10, 70, 10));
        assertEquals(stairs, world.getBlockData(10, 70, 10).getAsString());
        assertEquals(stairs, world.getBlockAt(10, 70, 10).getBlockData().getAsString());
        // A later plain write drops the stale properties.
        world.setBlockData(10, 70, 10, FerriteBlockData.create("minecraft:stone"));
        assertEquals("minecraft:stone", world.getBlockData(10, 70, 10).getAsString());
    }

    @Test void loadChunkAsksTheHostAndHonoursGenerate() {
        var calls = new java.util.ArrayList<String>();
        var generated = new java.util.concurrent.atomic.AtomicBoolean(false);
        HostBridge.transport = (owner, subject, method, args) -> {
            calls.add(method + "|" + args);
            return switch (method) {
                case "isChunkGenerated(int,int)" -> String.valueOf(generated.get());
                case "loadChunk(int,int)" -> { generated.set(true); yield "true"; }
                default -> "";
            };
        };
        try {
            assertFalse(world.loadChunk(5, 6, false), "not generated and generate=false");
            assertFalse(calls.stream().anyMatch(c -> c.startsWith("loadChunk")), calls.toString());
            assertTrue(world.loadChunk(5, 6, true));
            assertTrue(calls.stream().anyMatch(c -> c.startsWith("loadChunk(int,int)|5" + HostBridge.ARG + "6")), calls.toString());
            assertTrue(world.loadChunk(5, 6, false), "generated by now");
        } finally { HostBridge.transport = null; }
    }
}
