import java.lang.reflect.*;
import java.util.*;

/**
 * Generates a stub class whose every abstract method is routed to the host through HostBridge.
 * Usage: Generate &lt;interface&gt; &lt;ClassName&gt; &lt;public|package&gt; &lt;owner label&gt; &lt;subject expression&gt;
 * The subject expression is Java evaluated inside the stub (for example getUniqueId().toString()).
 */
public class Generate {
  static String t(Type t) { return t.getTypeName().replace('$','.'); }
  static String erased(Class<?> c) { return c.getCanonicalName() != null ? c.getCanonicalName() : c.getName(); }
  public static void main(String[] args) throws Exception {
    Class<?> c=Class.forName(args[0]);
    String cls=args[1]; boolean pub=args[2].equals("public"); String owner=args[3]; String subject=args[4];
    System.out.println("package dev.ferrite.server;\n// Generated by tools/Generate.java: every method is routed to the host via HostBridge.\n@SuppressWarnings({\"deprecation\",\"unchecked\",\"rawtypes\"})\n"+(pub?"public ":"")+"abstract class "+cls+" implements "+c.getCanonicalName()+" {");
    Map<String,Method> ms=new TreeMap<>();
    for(Method m:c.getMethods()) if(Modifier.isAbstract(m.getModifiers())) {
      String k=m.getName()+Arrays.toString(m.getParameterTypes()); Method old=ms.get(k);
      if(old==null || old.getReturnType().isAssignableFrom(m.getReturnType())) ms.put(k,m);
    }
    for(Method m:ms.values()) {
      StringBuilder b=new StringBuilder("public ");
      TypeVariable<Method>[] vars=m.getTypeParameters();
      if(vars.length>0) { b.append("<"); for(int i=0;i<vars.length;i++) { if(i>0)b.append(", "); b.append(vars[i].getName()); Type[] bounds=vars[i].getBounds(); if(!(bounds.length==1&&bounds[0]==Object.class)){b.append(" extends "); for(int j=0;j<bounds.length;j++){if(j>0)b.append(" & ");b.append(t(bounds[j]));}} } b.append("> "); }
      b.append(t(m.getGenericReturnType())).append(" ").append(m.getName()).append("(");
      Type[] ps=m.getGenericParameterTypes(); for(int i=0;i<ps.length;i++){if(i>0)b.append(", ");b.append(t(ps[i])).append(" a").append(i);} b.append(") { ");
      StringBuilder key=new StringBuilder(m.getName()).append("(");
      Class<?>[] raw=m.getParameterTypes(); for(int i=0;i<raw.length;i++){if(i>0)key.append(",");key.append(raw[i].getSimpleName());} key.append(")");
      StringBuilder call=new StringBuilder("(\""+owner+"\", "+subject+", \""+key+"\"");
      Class<?> r=m.getReturnType();
      boolean prim=r.isPrimitive();
      String fn;
      if(r==void.class) fn="callVoid"; else if(prim) fn="call"+Character.toUpperCase(r.getName().charAt(0))+r.getName().substring(1);
      else { fn="call"; call.append(", ").append(erased(r)).append(".class"); }
      for(int i=0;i<ps.length;i++) call.append(", a").append(i);
      call.append(")");
      if(r==void.class) b.append("HostBridge.").append(fn).append(call).append("; }");
      else if(prim) b.append("return HostBridge.").append(fn).append(call).append("; }");
      else b.append("return (").append(t(m.getGenericReturnType())).append(") HostBridge.").append(fn).append(call).append("; }");
      System.out.println(b);
    }
    System.out.println("}");
  }
}
